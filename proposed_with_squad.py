def detect_entities_hf(text: str) -> List[Dict[str, Any]]:
    try:
        ents = ner(text)
    except Exception:
        ents = []
    out = []
    for e in ents:
        out.append({
            "text": e.get("word"),
            "label": e.get("entity_group", e.get("entity")),
            "start": int(e.get("start", 0)),
            "end": int(e.get("end", 0))
        })
    return out

