# Chunk 8: Hybrid retriever that searches both node_index and rel_index
def kg_hybrid_retrieve(query: str, top_k: int = 5, alpha: float = 0.6):
    """
    alpha: weight for node score; (1-alpha) weight for relation score.
    Returns combined top_k results with fields: {'type': 'node'|'relation', 'id': id, 'score': float, 'text': text}
    """
    q_emb = embed_model.encode([query], convert_to_numpy=True)
    qn = normalize_np(q_emb).astype("float32")

    node_results = []
    rel_results = []

    if _HAS_FAISS:
        Dn, In = node_index.search(qn, top_k)
        Dr, Ir = rel_index.search(qn, top_k)
        for score, idx in zip(Dn[0], In[0]):
            node_results.append(("node", int(idx), float(score)))
        for score, idx in zip(Dr[0], Ir[0]):
            rel_results.append(("relation", int(idx), float(score)))
    else:
        dists_node, idxs_node = node_nn.kneighbors(qn, n_neighbors=top_k)
        dists_rel, idxs_rel = rel_nn.kneighbors(qn, n_neighbors=top_k)
        for dist, idx in zip(dists_node[0], idxs_node[0]):
            sim = 1 - float(dist)
            node_results.append(("node", int(idx), sim))
        for dist, idx in zip(dists_rel[0], idxs_rel[0]):
            sim = 1 - float(dist)
            rel_results.append(("relation", int(idx), sim))

    merged = []
    for t, idx, s in node_results:
        merged.append((t, idx, alpha * s))
    for t, idx, s in rel_results:
        merged.append((t, idx, (1 - alpha) * s))
    merged_sorted = sorted(merged, key=lambda x: x[2], reverse=True)[:top_k]

    results = []
    for t, idx, score in merged_sorted:
        if t == "node":
            text = node_texts_masked[idx]
            id_out = node_ids[idx]
        else:
            text = relation_texts_masked[idx]
            id_out = relation_ids[idx]
        results.append({"type": t, "id": id_out, "score": float(score), "text": text})
    return results

