def coarsen_date_to_year(date_text: str) -> str:
    m = re.search(r'\b(19|20)\d{2}\b', date_text)
    if m:
        return f"[DATE:{m.group(0)}]"
    return "[DATE]"

# dp noise function (same as you had)
def dp_age_noise(age_value: int, epsilon: float = 1.0) -> int:
    try:
        a = int(age_value)
    except Exception:
        return age_value
    noise = np.random.laplace(0, 1.0 / max(epsilon, 1e-6))
    noisy = int(round(a + noise))
    if noisy < 0 or noisy > 120:
        noisy = max(0, min(120, a + int(round(np.sign(noise) * min(10, abs(noise))))))
    return noisy

def mask_or_coarsen_age(span_text: str, dp_epsilon: float = 1.0, mode: str = "dp"):
    if dosage_pattern.search(span_text):
        return span_text
    m = re.search(r'(\d{1,3})', span_text)
    if not m:
        return "[AGE]"
    val = int(m.group(1))
    if mode == "mask":
        return "[AGE]"
    if mode == "range":
        r = 5
        low = max(0, val - r)
        high = val + r
        return f"[AGE:{low}-{high}]"
    noisy = dp_age_noise(val, epsilon=dp_epsilon)
    return f"[AGE:{noisy}]"

def mask_area_text(text: str) -> str:
    facility_pattern = re.compile(
        r"\b([A-Z][a-z]+(?:\s+[A-Z][a-z]+){0,3}\s+(Hospital|Clinic|Center|Surgery|Care|Medical|Health))\b",
        flags=re.IGNORECASE
    )
    text = facility_pattern.sub("[AREA]", text)
    area_terms = ["Hospital", "Clinic", "Center", "Surgery", "Medical Center", "Health Center", "Care Center"]
    for term in area_terms:
        text = re.sub(rf"\b{re.escape(term)}\b", "[AREA]", text, flags=re.IGNORECASE)
    return text

# Reuse your entity-aware masking function but apply to short node strings.
# It will run NER/fallback again on that small text (ok for node-level masking).
def apply_upp_to_span(span_text: str, dp_age: bool = True, dp_age_epsilon: float = 1.0) -> str:
    # detect entities in this small span (uses detect_entities_hf with fallback)
    ents = detect_entities_hf(span_text)
    out = span_text
    for ent in sorted(ents, key=lambda x: x["start"], reverse=True):
        lbl = ent.get("label", "").upper()
        s, e = ent["start"], ent["end"]
        span = ent["text"]
        if any(k in lbl for k in ["PERSON", "PATIENT", "NAME"]):
            out = out[:s] + "[PERSON]" + out[e:]
        elif any(k in lbl for k in ["ORG", "HOSPITAL", "FACILITY", "ORGANIZATION"]):
            out = out[:s] + "[HEALTHCARE_FACILITY]" + out[e:]
        elif any(k in lbl for k in ["LOC", "GPE", "LOCATION", "CITY", "AREA", "COUNTRY"]):
            out = out[:s] + "[AREA]" + out[e:]
        elif "DATE" in lbl or "TIME" in lbl:
            coarse = coarsen_date_to_year(span)
            out = out[:s] + coarse + out[e:]
        elif any(k in lbl for k in ["ID", "NUMBER"]) and len(re.sub(r'\s', '', span)) >= 5:
            out = out[:s] + "[ID]" + out[e:]
        elif "AGE" in lbl:
            if dp_age:
                replaced = mask_or_coarsen_age(span, dp_epsilon=dp_age_epsilon, mode="dp")
            else:
                replaced = mask_or_coarsen_age(span, dp_epsilon=dp_age_epsilon, mode="range")
            out = out[:s] + replaced + out[e:]
        else:
            pass

    # regex fallbacks for node-level
    out = re.sub(r'\b(John|Jane|Doe|Smith|Ali|Patient|Baby|child|father|mother|son|daughter)\b', '[PERSON]', out, flags=re.IGNORECASE)
    out = re.sub(r'\b(Mayo\s+Clinic|City\s+Health\s+Center|Green\s+Valley\s+Surgery\s+Center|Central\s+Hospital|QuickMeds)\b',
                 '[HEALTHCARE_FACILITY]', out, flags=re.IGNORECASE)
    out = re.sub(r'\b(London|New York|California|Islamabad|Karachi)\b', '[AREA]', out, flags=re.IGNORECASE)
    out = re.sub(RE_DATE_ISO, lambda m: coarsen_date_to_year(m.group(0)), out)
    out = re.sub(RE_RELATIVE_DATE, '[DATE]', out)
    out = re.sub(RE_ID_LONG, '[ID]', out)
    out = mask_area_text(out)
    return out

