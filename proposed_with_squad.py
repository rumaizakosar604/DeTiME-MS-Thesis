import re

# patterns that should NEVER appear in masked nodes
ARCHITECTURE_WORDS = [
    "Main Building", "Basilica of the Sacred Heart", "Grotto",
    "Gold Dome", "Virgin Mary"
]

DATE_PATTERN = re.compile(r'\b(19|20)\d{2}[/-]\d{1,2}[/-]\d{1,2}\b', flags=re.IGNORECASE)
ID_PATTERN = re.compile(r'\b\d{5,}\b')

def is_leaky(original, masked):
    """Return True if masked still leaks sensitive info."""
    o = original.lower()
    m = masked.lower()

    # architecture/entity leak
    for w in ARCHITECTURE_WORDS:
        if w.lower() in m and w.lower() in o:
            return True

    # explicit date leak
    if DATE_PATTERN.search(m):
        return True

    # ID leak
    if ID_PATTERN.search(m):
        return True

    return False

