def extract_relations_transformer(text: str, entities: List[Dict[str, Any]]) -> List[Tuple[str,str,str]]:
    rels = []
    if not use_re_model or len(entities) < 2:
        return rels
    for e1 in entities:
        for e2 in entities:
            if e1 == e2:
                continue
            marked = (text[:e1["start"]] + "[E1]" + e1["text"] + "[/E1]" + text[e1["end"]:e2["start"]] +
                     "[E2]" + e2["text"] + "[/E2]" + text[e2["end"]:])
            inputs = re_tokenizer(marked, truncation=True, max_length=256, return_tensors="pt").to(device)
            with torch.no_grad():
                out = re_model(**inputs)
                pred = torch.argmax(out.logits, dim=1).item()
                label = re_id2label.get(pred, str(pred))
                if label and label.lower() not in ("no_relation","0"):
                    rels.append((e1["text"], label, e2["text"]))
    return rels

def extract_relations_heuristic(text: str, entities: List[Dict[str, Any]]) -> List[Tuple[str,str,str]]:
    rels = []
    s_text = text.lower()
    for e1 in entities:
        for e2 in entities:
            if e1 == e2:
                continue
            if "prescrib" in s_text or "given" in s_text or "prescribed" in s_text or "mg" in s_text:
                rels.append((e1["text"], "MEDICATED_WITH", e2["text"]))
            elif "visit" in s_text or "visited" in s_text or "appointment" in s_text:
                rels.append((e1["text"], "VISITED", e2["text"]))
            elif "diagnos" in s_text or "diagnosed" in s_text:
                rels.append((e1["text"], "DIAGNOSED_WITH", e2["text"]))
    rels = list(set(rels))
    return rels

def extract_relations(text: str, entities: List[Dict[str, Any]]) -> List[Tuple[str,str,str]]:
    rels = extract_relations_transformer(text, entities)
    if not rels:
        rels = extract_relations_heuristic(text, entities)
    return rels

# Chunk 5: Build Knowledge Graph from cleaned texts; collect node map & relations
def build_kg_and_maps(texts: List[str]):
    G = nx.Graph()
    node_texts = []  # list of node texts (original)
    node_map = {}    # node_id -> {"text":..., "label":..., "doc_id":...}
    relations = []   # list of (node_id_h, relation_label, node_id_t, doc_id)

    for i, text in enumerate(texts):
        ents = detect_entities_hf(text)
        # add nodes
        for e in ents:
            node_id = f"{i}:{e['text']}:{e['label']}"
            if node_id not in node_map:
                node_map[node_id] = {"text": e["text"], "label": e["label"], "doc_id": i}
                node_texts.append(e["text"])
                G.add_node(node_id, label=e['label'], text=e['text'], doc_id=i)
        # extract relations for this doc
        rels = extract_relations(text, ents)
        for h, r, t in rels:
            # find node ids within this doc for h and t (prefer exact text match)
            possible_h = [nid for nid,meta in node_map.items() if meta["text"]==h and meta["doc_id"]==i]
            possible_t = [nid for nid,meta in node_map.items() if meta["text"]==t and meta["doc_id"]==i]
            if possible_h and possible_t:
                node_h = possible_h[0]
                node_t = possible_t[0]
                relations.append((node_h, r, node_t, i))
                G.add_edge(node_h, node_t, relation=r, doc_id=i)
    return G, node_map, relations

