# apply gaussian DP noise (on the embedding vectors)
def add_gaussian_noise_matrix(mat, sigma=0.0):
    if sigma <= 0.0:
        return mat
    noise = np.random.normal(0, sigma, size=mat.shape)
    return mat + noise

emb_matrix_dp = add_gaussian_noise_matrix(emb_matrix, sigma=DP_SIGMA)

