def coarsen_simple(text):
    if not text:
        return text

    # 1️⃣ Replace explicit dates (YYYY-MM-DD, DD/MM/YYYY, etc.)
    text = re.sub(r"\b\d{4}[-/.]\d{2}[-/.]\d{2}\b", "[DATE]", text)
    text = re.sub(r"\b\d{1,2}[-/]\d{1,2}[-/]\d{2,4}\b", "[DATE]", text)

    # 2️⃣ Replace day names
    for day in DAYS:
        text = re.sub(rf"\b{day}\b", "[DAY]", text, flags=re.IGNORECASE)

    # 3️⃣ Replace age patterns
    text = re.sub(r"\bage\s*\d{1,3}\b", "[AGE]", text, flags=re.IGNORECASE)
    text = re.sub(r"\b\d{1,3}[- ]?year[- ]?old\b", "[AGE]", text, flags=re.IGNORECASE)

    return text

