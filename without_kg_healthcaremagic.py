def dense_search_faiss(query_vec, top_k=TOP_K):
    # returns (indices, scores)
    qv = query_vec.astype("float32")
    qn = qv / (np.linalg.norm(qv) + 1e-9)
    if _HAS_FAISS:
        D, I = index.search(qn.reshape(1, -1), top_k)
        return I[0].tolist(), D[0].tolist()
    else:
        # sklearn NearestNeighbors returns distances; convert to similarity-like score (1 - dist)
        dists, idxs = nn.kneighbors(qn.reshape(1, -1), n_neighbors=top_k)
        sims = (1 - dists[0]).tolist()
        return idxs[0].tolist(), sims

def hybrid_search(query, top_k=TOP_K, alpha=ALPHA):
    # BM25 scores
    q_tokens = query.split()
    bm25_scores = bm25.get_scores(q_tokens)  # length = len(df)
    if bm25_scores.max() == 0:
        bm25_norm = bm25_scores
    else:
        bm25_norm = bm25_scores / (bm25_scores.max() + 1e-9)
    # Dense scores
    q_emb = embedder.encode([query], convert_to_numpy=True)[0]
    # search dense
    idxs, dense_scores = dense_search_faiss(q_emb, top_k=len(df))
    dense_full = np.zeros(len(df))
    dense_full[idxs] = dense_scores
    if dense_full.max() == 0:
        dense_norm = dense_full
    else:
        dense_norm = dense_full / (dense_full.max() + 1e-9)
    # combine: final_score = (1-alpha) * dense + alpha * bm25  (you can swap semantics easily)
    final = (1 - alpha) * dense_norm + alpha * bm25_norm
    top_idx = np.argsort(-final)[:top_k]
    top_scores = final[top_idx]
    return top_idx.tolist(), top_scores.tolist()

