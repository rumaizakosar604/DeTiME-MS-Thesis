import re

# regex patterns for PII with labels
PII_PATTERNS = {
    r"\b\d{4,}\b": "[ID]",
    r"\b\d{1,2}[-/.]\d{1,2}[-/.]\d{2,4}\b": "[DATE]",
    r"\b\d{3}[-.]\d{3}[-.]\d{4}\b": "[PHONE]",
    r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}": "[EMAIL]"
}

def mask_with_labels(text, entities):
    if not text:
        return text

    # mask NER spans with their labels
    spans = sorted([(max(0, e["start"]), min(len(text), e["end"]), e["label"]) for e in entities], key=lambda x: x[0])
    masked = []
    last = 0
    for start, end, label in spans:
        masked.append(text[last:start])
        masked.append(f"[{label}]")  # use the label as mask
        last = end
    masked.append(text[last:])
    masked_text = "".join(masked)

    # mask regex PII with type
    for pattern, label in PII_PATTERNS.items():
        masked_text = re.sub(pattern, label, masked_text)

    return masked_text

