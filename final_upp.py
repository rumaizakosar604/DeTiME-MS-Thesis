def detect_entities_fallback(text: str) -> List[Dict[str, Any]]:
    """
    Heuristic fallback: detect common names, patient tokens, orgs, locations, diseases,
    dates, ids, and medication dosages.
    Returns list of entities in format: {'text':..., 'label':..., 'start':..., 'end':...}
    """
    out = []
    text_low = text.lower()

    # Names & patient tokens
    for name in (COMMON_NAMES + COMMON_PATIENT_TOKENS):
        for m in re.finditer(r'\b' + re.escape(name) + r'\b', text_low, flags=re.IGNORECASE):
            s, e = m.start(), m.end()
            out.append({"text": text[s:e], "label": "PERSON", "start": s, "end": e})

    # Orgs
    for org in COMMON_ORGS:
        for m in re.finditer(re.escape(org), text_low, flags=re.IGNORECASE):
            s, e = m.start(), m.end()
            out.append({"text": text[s:e], "label": "ORG", "start": s, "end": e})

    # Locations
    for loc in COMMON_LOCATIONS:
        for m in re.finditer(r'\b' + re.escape(loc) + r'\b', text_low, flags=re.IGNORECASE):
            s, e = m.start(), m.end()
            out.append({"text": text[s:e], "label": "LOCATION", "start": s, "end": e})

    # Diseases lexicon
    for d in DISEASE_LEXICON:
        for m in re.finditer(r'\b' + re.escape(d) + r'\b', text_low, flags=re.IGNORECASE):
            s, e = m.start(), m.end()
            out.append({"text": text[s:e], "label": "DISEASE", "start": s, "end": e})

    # Dates (ISO-like)
    for m in RE_DATE_ISO.finditer(text):
        s, e = m.start(), m.end()
        out.append({"text": text[s:e], "label": "DATE", "start": s, "end": e})

    # Long numeric IDs
    for m in RE_ID_LONG.finditer(text):
        s, e = m.start(), m.end()
        out.append({"text": text[s:e], "label": "ID", "start": s, "end": e})

    # Dosage detection (mark as DOSAGE so we don't treat them as AGE later)
    for m in DOSAGE_PATTERN.finditer(text):
        s, e = m.start(), m.end()
        out.append({"text": text[s:e], "label": "DOSAGE", "start": s, "end": e})

    # Deduplicate by span+label
    seen = set()
    uniq = []
    for ent in sorted(out, key=lambda x: (x["start"], -x["end"])):
        key = (ent["start"], ent["end"], ent["label"])
        if key not in seen:
            seen.add(key)
            uniq.append(ent)
    return uniq

def postprocess_entities_remove_age_dosage(entities: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Post-process entity list to avoid AGE mislabels:
     - If an entity has label AGE (or NUMBER-like) but overlaps a DOSAGE span or matches DOSAGE_PATTERN,
       relabel it to DOSAGE or remove AGE label.
     - Keep a consistent single label per entity (prefer non-sensitive DOSAGE).
    """
    # first, build an index of dosage spans from entities
    dosage_spans = [(e["start"], e["end"]) for e in entities if e["label"] == "DOSAGE"]
    out = []
    for e in entities:
        lbl = e["label"].upper()
        txt = e["text"]
        s, t = e["start"], e["end"]
        # if labeled AGE but overlaps dosage_span -> treat as DOSAGE
        if lbl in ("AGE", "NUMBER", "NUM"):
            overlaps_dosage = any(not (t <= ds or s >= de) for ds, de in dosage_spans)
            if overlaps_dosage or DOSAGE_PATTERN.search(txt):
                # convert to DOSAGE (non-sensitive for age)
                out.append({"text": e["text"], "label": "DOSAGE", "start": s, "end": t})
                continue
        # if any label (even PERSON/ORG) but the text matches DOSAGE_PATTERN, mark as DOSAGE
        if DOSAGE_PATTERN.search(txt) and lbl != "DOSAGE":
            out.append({"text": e["text"], "label": "DOSAGE", "start": s, "end": t})
            continue
        # otherwise keep original
        out.append(e)
    # dedupe and prefer longer spans when overlapping
    merged_sorted = sorted(out, key=lambda x: (x["start"], -x["end"]))
    final = []
    last_end = -1
    for item in merged_sorted:
        if item["start"] >= last_end:
            final.append(item)
            last_end = item["end"]
        else:
            # overlap: keep longer span
            if item["end"] > final[-1]["end"]:
                final[-1] = item
                last_end = item["end"]
    return final

def detect_entities_final(text: str) -> List[Dict[str, Any]]:
    """
    Wrapper used across pipeline:
      - runs hybrid NER (general + biomed)
      - augments with fallback lexicon detections
      - marks dosages as DOSAGE
      - removes/relables AGE entities that are actually dosages
    Returns deduplicated entities sorted by start.
    """
    # run hybrid detector (general + biomed)
    try:
        base = detect_entities_hybrid(text)
    except Exception:
        base = []

    # get fallback entities
    fallback = detect_entities_fallback(text)

    # merge: prefer base spans, add fallback if new
    merged = []
    covered = set((e["start"], e["end"]) for e in base)
    merged.extend(base)
    for f in fallback:
        if (f["start"], f["end"]) not in covered:
            merged.append(f)

    # Post-process to remove AGE false positives that are dosages
    merged = postprocess_entities_remove_age_dosage(merged)

    # final dedupe: prefer longer spans when overlapping
    merged_sorted = sorted(merged, key=lambda x: (x["start"], -x["end"]))
    final = []
    last_end = -1
    for e in merged_sorted:
        if e["start"] >= last_end:
            final.append(e)
            last_end = e["end"]
        else:
            if e["end"] > final[-1]["end"]:
                final[-1] = e
                last_end = e["end"]
    return final

