def extract_relations_transformer(text: str, entities: List[Dict[str, Any]]) -> List[Tuple[str,str,str]]:
    rels = []
    if not use_re_model or len(entities) < 2:
        return rels
    for e1 in entities:
        for e2 in entities:
            if e1 == e2: continue
            marked = (text[:e1["start"]] + "[E1]" + e1["text"] + "[/E1]" + text[e1["end"]:e2["start"]] +
                      "[E2]" + e2["text"] + "[/E2]" + text[e2["end"]:])
            inputs = re_tokenizer(marked, truncation=True, max_length=256, return_tensors="pt").to(device)
            with torch.no_grad():
                out = re_model(**inputs)
                pred = int(torch.argmax(out.logits, dim=1).item())
                lab = re_id2label.get(pred, str(pred))
                if lab and lab.lower() not in ("no_relation","0"):
                    rels.append((e1["text"], lab, e2["text"]))
    return list(set(rels))

def extract_relations_heuristic(text: str, entities: List[Dict[str, Any]]) -> List[Tuple[str,str,str]]:
    rels = []
    s_text = text.lower()
    for e1 in entities:
        for e2 in entities:
            if e1 == e2: continue
            if any(token in s_text for token in ["prescrib", "given", "mg", "tablet", "dose", "dosing"]):
                rels.append((e1["text"], "MEDICATED_WITH", e2["text"]))
            if any(token in s_text for token in ["visit","visited","ward","clinic","appointment"]):
                rels.append((e1["text"], "VISITED", e2["text"]))
            if any(token in s_text for token in ["diagnos","diagnosed","diagnosis"]):
                rels.append((e1["text"], "DIAGNOSED_WITH", e2["text"]))
    return list(set(rels))

def extract_relations(text: str, entities: List[Dict[str, Any]]):
    r = extract_relations_transformer(text, entities)
    if not r:
        r = extract_relations_heuristic(text, entities)
    return r

