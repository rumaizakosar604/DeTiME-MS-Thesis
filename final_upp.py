def hybrid_retrieve(query: str, top_k: int = 5, alpha: float = 0.6):
    q_emb = embed_model.encode([query], convert_to_numpy=True)
    qn = normalize_np(q_emb).astype("float32")

    doc_results = []
    node_results = []

    if _HAS_FAISS:
        Dd, Id = doc_index.search(qn, top_k)
        Dn, In = node_index.search(qn, top_k)
        for score, idx in zip(Dd[0], Id[0]):
            doc_results.append(("doc", int(idx), float(score)))
        for score, idx in zip(Dn[0], In[0]):
            node_results.append(("node", int(idx), float(score)))
    else:
        dists_doc, idxs_doc = doc_nn.kneighbors(qn, n_neighbors=top_k)
        dists_node, idxs_node = node_nn.kneighbors(qn, n_neighbors=top_k)
        for dist, idx in zip(dists_doc[0], idxs_doc[0]):
            sim = 1 - float(dist)
            doc_results.append(("doc", int(idx), sim))
        for dist, idx in zip(dists_node[0], idxs_node[0]):
            sim = 1 - float(dist)
            node_results.append(("node", int(idx), sim))

    merged = []
    for t, idx, s in doc_results:
        merged.append((t, idx, alpha * s))
    for t, idx, s in node_results:
        merged.append((t, idx, (1 - alpha) * s))
    merged_sorted = sorted(merged, key=lambda x: x[2], reverse=True)[:top_k]

    results = []
    for t, idx, score in merged_sorted:
        if t == "doc":
            text = doc_texts[idx]
        else:
            text = node_texts[idx]
        results.append({"type": t, "index": idx, "score": float(score), "text": text})
    return results

