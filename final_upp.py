def compute_privacy_leakage(original_texts: List[str], perturbed_texts: List[str]) -> Dict[str, Any]:
    sensitive_types = ["PERSON", "ORG", "DATE", "ID", "AGE", "AREA"]
    totals = {t:0 for t in sensitive_types}
    leaked_counts = {t:0 for t in sensitive_types}
    leaked_examples = {t:[] for t in sensitive_types}

    for orig, pert in zip(original_texts, perturbed_texts):
        ents = detect_entities_hf(orig)
        for e in ents:
            lbl = e.get("label","").upper()
            if any(k in lbl for k in ["PERSON","NAME","PATIENT"]):
                t = "PERSON"
            elif any(k in lbl for k in ["ORG","HOSPITAL","FACILITY"]):
                t = "ORG"
            elif any(k in lbl for k in ["DATE","TIME"]):
                t = "DATE"
            elif any(k in lbl for k in ["ID","NUMBER"]):
                t = "ID"
            elif "AGE" in lbl:
                t = "AGE"
            elif any(k in lbl for k in ["LOC","GPE","LOCATION","CITY","AREA"]):
                t = "AREA"
            else:
                t = None

            if t:
                totals[t] += 1
                if e["text"] in pert:
                    leaked_counts[t] += 1
                    leaked_examples[t].append({"text": e["text"], "orig_doc": orig})

    overall_total = sum(totals.values())
    overall_leaked = sum(leaked_counts.values())
    if overall_leaked > 0:
        leakage_value = overall_total / overall_leaked
    else:
        leakage_value = float("inf")

    leak_rates = {t: (leaked_counts[t] / totals[t] if totals[t]>0 else None) for t in sensitive_types}
    return {
        "per_type": {"total": totals, "leaked": leaked_counts, "leak_rate": leak_rates, "leaked_examples": leaked_examples},
        "overall": {"total_sensitive": overall_total, "leaked_sensitive": overall_leaked, "privacy_leakage_metric": leakage_value}
    }

