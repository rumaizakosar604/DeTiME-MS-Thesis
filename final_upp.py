def build_kg_and_nodes(texts: List[str]):
    G = nx.Graph()
    node_texts = []
    for i, t in enumerate(texts):
        doc_node = f"doc:{i}"
        G.add_node(doc_node, label="DOC", text=f"doc_{i}", doc_id=i)
        ents = detect_entities_hf(t)
        for e in ents:
            n = f"{i}:{e['start']}:{e['end']}:{e['text']}"
            if not G.has_node(n):
                G.add_node(n, label=e["label"], text=e["text"], doc_id=i)
                node_texts.append(e["text"])
            G.add_edge(doc_node, n, relation="MENTIONS")
        rels = extract_relations(t, ents)
        for h, r, tt in rels:
            possible_h = [n for n,d in G.nodes(data=True) if d.get("text")==h and d.get("doc_id")==i]
            possible_t = [n for n,d in G.nodes(data=True) if d.get("text")==tt and d.get("doc_id")==i]
            if possible_h and possible_t:
                G.add_edge(possible_h[0], possible_t[0], relation=r, doc_id=i)
    return G, node_texts

