# Dosage pattern (important: dosages are NOT ages)
dosage_pattern = re.compile(
    r"\b\d+\s?(mg|mcg|g|gram|grams|kg|ml|mL|L|units|IU|tablet|tablets|capsule|capsules|tab|tabs|hour|hours|hr|hrs|dose|doses)\b",
    flags=re.IGNORECASE
)
def is_dosage(text):
    return bool(dosage_pattern.search(text))

# Age mask that does NOT mask dosages
def mask_age(text: str):
    def skip_if_dosage(m):
        match_text = m.group(0)
        if is_dosage(match_text):
            return match_text
        return "[AGE]"
    age_patterns = [
        r"\b\d{1,3}-year-old\b",
        r"\bage\s+\d{1,3}\b",
        r"\b\d{1,3}\s?y/o\b",
        r"\b\d{1,3}\s?years?\s?old\b",
    ]
    for pat in age_patterns:
        text = re.sub(pat, skip_if_dosage, text, flags=re.IGNORECASE)
    return text

# Area/facility masking improved
def mask_area(text: str):
    facility_pattern = re.compile(
        r"\b([A-Z][a-z]+(?:\s+[A-Z][a-z]+){0,3}\s+(Hospital|Clinic|Center|Surgery|Care|Medical|Health))\b",
        flags=re.IGNORECASE
    )
    text = facility_pattern.sub("[AREA]", text)
    area_terms = [
        "Hospital", "Clinic", "Center", "Surgery",
        "Medical Center", "Health Center", "Care Center"
    ]
    for term in area_terms:
        text = re.sub(rf"\b{re.escape(term)}\b", "[AREA]", text, flags=re.IGNORECASE)
    return text

# Final UPP application
def apply_upp_masking_only(text: str) -> str:
    # run entity-aware masking first (to target known spans) + then pattern-based replacements
    ents = detect_entities_hf(text)
    out = text
    # mask by entity spans (reverse order)
    for ent in sorted(ents, key=lambda x: x["start"], reverse=True):
        s, e = ent["start"], ent["end"]
        lbl = ent["label"].upper()
        orig = out[s:e]
        if any(k in lbl for k in ["PERSON","PATIENT","NAME"]):
            out = out[:s] + "[PERSON]" + out[e:]
        elif any(k in lbl for k in ["ORG","HOSPITAL","FACILITY","ORGANIZATION"]):
            out = out[:s] + "[HEALTHCARE_FACILITY]" + out[e:]
        elif any(k in lbl for k in ["LOC","GPE","LOCATION","CITY","AREA"]):
            out = out[:s] + "[AREA]" + out[e:]
        elif any(k in lbl for k in ["DATE","TIME"]):
            # coarsen to year if possible
            ym = re.search(r'\b(19|20)\d{2}\b', orig)
            if ym:
                out = out[:s] + f"[DATE:{ym.group(0)}]" + out[e:]
            else:
                out = out[:s] + "[DATE]" + out[e:]
        elif any(k in lbl for k in ["ID","NUMBER"]) and len(re.sub(r'\s','',orig))>=5:
            out = out[:s] + "[ID]" + out[e:]
        elif "AGE" in lbl:
            # apply mask_age to the substring
            masked = mask_age(orig)
            out = out[:s] + masked + out[e:]
        else:
            # leave other tokens (DISEASE, DRUG, SYMPTOM) unchanged
            pass

    # regex fallbacks after span-level masking
    # protect dosages (do nothing)
    # coarsen ISO dates
    out = re.sub(r'\b(19|20)\d{2}[/-]\d{1,2}[/-]\d{1,2}\b', lambda m: "[DATE:"+re.search(r'\b(19|20)\d{2}\b', m.group(0)).group(0)+"]", out)
    out = re.sub(r'\b(yesterday|today|tomorrow|next monday|last week|next week)\b', "[DATE]", out, flags=re.IGNORECASE)
    # replace long numeric ids
    out = re.sub(r'\b\d{5,}\b', "[ID]", out)

    # apply improved area masking
    out = mask_area(out)

    # extra fallback replacements for names/orgs
    out = re.sub(r'\b(' + r'|'.join(re.escape(tok) for tok in COMMON_PATIENT_TOKENS) + r')\b', '[PERSON]', out, flags=re.IGNORECASE)
    out = re.sub(r'\b(' + r'|'.join(re.escape(org) for org in COMMON_ORGS) + r')\b', '[HEALTHCARE_FACILITY]', out, flags=re.IGNORECASE)
    out = re.sub(r'\b(' + r'|'.join(re.escape(n) for n in COMMON_NAMES) + r')\b', "[PERSON]", out, flags=re.IGNORECASE)

    return out

